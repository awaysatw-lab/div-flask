window.changeLanguage =
    function (langCode) {

        console.log(
            "선택한 언어:",
            langCode
        );

        if (
            !langTextMap[langCode]
        ) {

            console.error(
                "지원하지 않는 언어:",
                langCode
            );

            return;
        }

        localStorage.setItem(
            "selected_lang",
            langCode
        );

        updateLanguageText(
            langCode
        );

        const menu =
            document.getElementById(
                "customLangMenu"
            );

        if (menu) {

            menu.style.display =
                "none";
        }

        translatePage(
            langCode
        );

        translateBanner(
            langCode
        );
    };


