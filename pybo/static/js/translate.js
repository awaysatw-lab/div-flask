// 번역 대상 텍스트 노드 찾기
// ======================================================

function getTextNodes() {

    const walker =
        document.createTreeWalker(
            document.body,
            NodeFilter.SHOW_TEXT,
            {
                acceptNode: function (node) {

                    const parent =
                        node.parentElement;

                    if (!parent) {
                        return NodeFilter.FILTER_REJECT;
                    }

                    const tagName =
                        parent.tagName.toLowerCase();

                    if (
                        tagName === "script" ||
                        tagName === "style" ||
                        tagName === "noscript"
                    ) {
                        return NodeFilter.FILTER_REJECT;
                    }

                    if (
                        parent.closest(
                            "#customLangMenu"
                        )
                    ) {
                        return NodeFilter.FILTER_REJECT;
                    }

                    if (
                        parent.closest(
                            "#languageDropdown"
                        )
                    ) {
                        return NodeFilter.FILTER_REJECT;
                    }

                    if (
                        !node.nodeValue.trim()
                    ) {
                        return NodeFilter.FILTER_REJECT;
                    }


                    return NodeFilter.FILTER_ACCEPT;
                }
            }
        );


    const nodes = [];

    let node;

    while (
        node = walker.nextNode()
    ) {
        nodes.push(node);
    }

    return nodes;
}


// ======================================================
// 문자열 번역
// ======================================================

function translateText(
    originalText,
    translationMap
) {

    let result =
        originalText;

    const keys =
        Object.keys(
            translationMap
        ).sort(
            function (a, b) {
                return b.length - a.length;
            }
        );


    keys.forEach(
        function (sourceText) {

            const targetText =
                translationMap[
                    sourceText
                ];


            if (
                result.includes(
                    sourceText
                )
            ) {

                result =
                    result.replaceAll(
                        sourceText,
                        targetText
                    );
            }

        }
    );


    return result;
}


