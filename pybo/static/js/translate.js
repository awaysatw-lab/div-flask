// 일반 페이지 번역
// ======================================================

function translatePage(langCode) {

    if (
        langCode === "ko"
    ) {

        restoreOriginalText();

        return;
    }


    const translationMap =
        translations[langCode];


    if (!translationMap) {
        return;
    }


    const textNodes =
        getTextNodes();


    textNodes.forEach(
        function (textNode) {

            if (
                textNode.__originalText === undefined
            ) {

                textNode.__originalText =
                    textNode.nodeValue;
            }


            const originalText =
                textNode.__originalText;


            const translatedText =
                translateText(
                    originalText,
                    translationMap
                );


            textNode.nodeValue =
                translatedText;
        }
    );
}


// ======================================================
// 한국어 원문 복구
// ======================================================

function restoreOriginalText() {

    const textNodes =
        getTextNodes();


    textNodes.forEach(
        function (textNode) {

            if (
                textNode.__originalText !== undefined
            ) {

                textNode.nodeValue =
                    textNode.__originalText;

                delete textNode.__originalText;
            }

        }
    );
}


// ======================================================
// 메인 배너 번역
// ======================================================

let bannerTranslationRunning = false;


function translateBanner(langCode) {

    const title =
        document.getElementById(
            "bannerTitle"
        );

    const desc =
        document.getElementById(
            "bannerDesc"
        );


    if (
        !title ||
        !desc
    ) {
        return;
    }


    // 한국어
    if (
        langCode === "ko"
    ) {

        if (
            title.dataset.original
        ) {

            title.innerHTML =
                title.dataset.original;
        }

        if (
            desc.dataset.original
        ) {

            desc.innerHTML =
                desc.dataset.original;
        }

        return;
    }


    const translationMap =
        translations[langCode];


    if (!translationMap) {
        return;
    }

    if (
        !title.dataset.original
    ) {

        title.dataset.original =
            title.innerHTML;
    }


    if (
        !desc.dataset.original
    ) {

        desc.dataset.original =
            desc.innerHTML;
    }


    let titleText =
        title.dataset.original;


    let descText =
        desc.dataset.original;


    titleText =
        translateText(
            titleText,
            translationMap
        );


    descText =
        translateText(
            descText,
            translationMap
        );


    bannerTranslationRunning = true;


    title.innerHTML =
        titleText;

    desc.innerHTML =
        descText;


    setTimeout(
        function () {
            bannerTranslationRunning =
                false;
        },
        50
    );
}


// ======================================================
// 배너 변경 감시
// ======================================================

function observeBanner() {

    const title =
        document.getElementById(
            "bannerTitle"
        );

    const desc =
        document.getElementById(
            "bannerDesc"
        );


    if (
        !title &&
        !desc
    ) {
        return;
    }


    const observer =
        new MutationObserver(
            function () {

                if (
                    bannerTranslationRunning
                ) {
                    return;
                }


                const currentLanguage =
                    localStorage.getItem(
                        "selected_lang"
                    ) || "ko";


                if (
                    currentLanguage === "ko"
                ) {
                    return;
                }

                if (title) {

                    title.dataset.original =
                        title.innerHTML;
                }


                if (desc) {

                    desc.dataset.original =
                        desc.innerHTML;
                }


                translateBanner(
                    currentLanguage
                );

            }
        );


    if (title) {

        observer.observe(
            title,
            {
                childList: true,
                subtree: true,
                characterData: true
            }
        );
    }


    if (desc) {

        observer.observe(
            desc,
            {
                childList: true,
                subtree: true,
                characterData: true
            }
        );
    }
}


