window.toggleLangMenu = function () {

    const menu =
        document.getElementById(
            "customLangMenu"
        );

    if (!menu) {
        return;
    }

    const currentDisplay =
        window.getComputedStyle(menu).display;

    if (currentDisplay === "none") {

        menu.style.display = "block";

    } else {

        menu.style.display = "none";
    }
};


